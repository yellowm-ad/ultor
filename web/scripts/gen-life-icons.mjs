function svg(shape, pal) {
  const rows = SHAPES[shape]
  const rects = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x]
      if (ch === '.') continue
      const col = ch === 'o' ? pal.o ?? '#241a12' : pal[ch]
      if (!col) continue
      rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${col}"/>`)
    }
  })
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="64" height="64" shape-rendering="crispEdges">${rects.join('')}</svg>\n`
}

